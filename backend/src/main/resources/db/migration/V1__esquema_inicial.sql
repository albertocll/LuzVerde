-- Esquema inicial de Luz Verde. Es el mismo que creaba Hibernate con ddl-auto: update.
-- Las bases de datos que ya existían se marcan como versión 1 sin ejecutar este script
-- (spring.flyway.baseline-on-migrate).

CREATE TABLE usuarios (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         varchar(254)                NOT NULL UNIQUE,
    password_hash varchar(255)                NOT NULL,
    nombre        varchar(100)                NOT NULL,
    creado_en     timestamp(6) with time zone NOT NULL
);

CREATE TABLE candidaturas (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint       NOT NULL REFERENCES usuarios (id),
    empresa    varchar(150) NOT NULL,
    puesto     varchar(150) NOT NULL,
    fecha      date         NOT NULL,
    estado     varchar(30)  NOT NULL
        CHECK (estado IN ('PENDIENTE', 'ENVIADA', 'ESPERANDO_RESPUESTA', 'ENTREVISTA', 'DESCARTADA')),
    enlace     varchar(500),
    notas      varchar(4000)
);
CREATE INDEX idx_candidaturas_usuario ON candidaturas (usuario_id);

CREATE TABLE perfiles (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     bigint NOT NULL UNIQUE REFERENCES usuarios (id),
    titular        varchar(150),
    telefono       varchar(30),
    ubicacion      varchar(150),
    modalidad      varchar(20) CHECK (modalidad IN ('PRESENCIAL', 'HIBRIDO', 'REMOTO')),
    salario_minimo integer,
    linkedin       varchar(200),
    github         varchar(200)
);

CREATE TABLE perfil_experiencias (
    perfil_id   bigint       NOT NULL REFERENCES perfiles (id),
    orden       integer      NOT NULL,
    empresa     varchar(150) NOT NULL,
    puesto      varchar(150) NOT NULL,
    inicio      varchar(7)   NOT NULL,
    fin         varchar(7),
    descripcion varchar(2000),
    PRIMARY KEY (orden, perfil_id)
);

CREATE TABLE perfil_formaciones (
    perfil_id bigint       NOT NULL REFERENCES perfiles (id),
    orden     integer      NOT NULL,
    titulo    varchar(200) NOT NULL,
    centro    varchar(150),
    inicio    varchar(7),
    fin       varchar(7),
    PRIMARY KEY (orden, perfil_id)
);

CREATE TABLE perfil_idiomas (
    perfil_id bigint      NOT NULL REFERENCES perfiles (id),
    orden     integer     NOT NULL,
    nombre    varchar(60) NOT NULL,
    nivel     varchar(60),
    PRIMARY KEY (orden, perfil_id)
);

CREATE TABLE perfil_proyectos (
    perfil_id   bigint       NOT NULL REFERENCES perfiles (id),
    orden       integer      NOT NULL,
    nombre      varchar(150) NOT NULL,
    descripcion varchar(2000),
    tecnologias varchar(500),
    enlace      varchar(500),
    PRIMARY KEY (orden, perfil_id)
);

CREATE TABLE perfil_tecnologias (
    perfil_id bigint      NOT NULL REFERENCES perfiles (id),
    orden     integer     NOT NULL,
    nombre    varchar(60) NOT NULL,
    nivel     varchar(20) NOT NULL CHECK (nivel IN ('SOLIDO', 'MEDIO', 'SIN_TOCAR')),
    PRIMARY KEY (orden, perfil_id)
);

CREATE TABLE evaluaciones (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id         bigint                      NOT NULL REFERENCES usuarios (id),
    oferta_texto       varchar(15000)              NOT NULL,
    empresa            varchar(150),
    puesto             varchar(150),
    semaforo           varchar(10)                 NOT NULL CHECK (semaforo IN ('VERDE', 'AMARILLO', 'ROJO')),
    resumen            varchar(1000),
    pros               varchar(8000),
    banderas_rojas     varchar(8000),
    huecos             varchar(8000),
    accion_recomendada varchar(1000),
    creado_en          timestamp(6) with time zone NOT NULL
);

CREATE TABLE cvs (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint                      NOT NULL REFERENCES usuarios (id),
    empresa    varchar(150),
    puesto     varchar(150),
    carta      varchar(2000),
    huecos     varchar(8000),
    pdf        bytea                       NOT NULL,
    docx       bytea                       NOT NULL,
    creado_en  timestamp(6) with time zone NOT NULL
);

CREATE TABLE usos_ia (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint                      NOT NULL,
    tipo       varchar(20)                 NOT NULL,
    creado_en  timestamp(6) with time zone NOT NULL
);
CREATE INDEX idx_usos_ia_usuario_fecha ON usos_ia (usuario_id, creado_en);
